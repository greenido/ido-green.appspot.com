#!/usr/bin/env node
/**
 * Renders www/data/projects.json into index.html between the PROJECTS markers.
 *
 * The cards are built here rather than in the browser on purpose: projects are
 * the main content of the site, so they have to be in the served HTML for
 * crawlers, link previews, and visitors without JS. Filtering and search are
 * layered on top of this markup as progressive enhancement.
 *
 * Run after editing projects.json:  node tools/build-projects.js
 */
const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const DATA = path.join(ROOT, 'www', 'data', 'projects.json');
const INDEX = path.join(ROOT, 'www', 'index.html');

const START = '<!-- PROJECTS:START (generated by tools/build-projects.js - edit data/projects.json) -->';
const END = '<!-- PROJECTS:END -->';

const ARROW = '<svg width="18" height="18" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2"><path d="M5 12h14M12 5l7 7-7 7"/></svg>';

function esc(s) {
  return String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;')
    .replace(/>/g, '&gt;').replace(/"/g, '&quot;');
}

function renderCard(p) {
  // The card is an <article>, not an <a>: a nested source link inside an anchor
  // would be invalid HTML. The main link is stretched over the whole card with
  // ::after instead, so the card still clicks through anywhere.
  // Three projects link straight at their repo, so a Source badge beside a
  // "View GitHub" call to action would be the same URL twice on one card.
  const repoUrl = p.repo ? `https://github.com/${p.repo}` : null;
  const showRepo = repoUrl && repoUrl !== p.url;

  const repo = showRepo
    ? `\n            <a class="project-repo" href="${esc(repoUrl)}" target="_blank" rel="noopener"
               aria-label="Source code for ${esc(p.title)}" data-repo="${esc(p.repo)}">Source</a>`
    : '';

  return `          <article class="glass-card project-card ${esc(p.category)}" id="project-${esc(p.id)}"
                   data-category="${esc(p.category)}" data-tags="${esc((p.tags || []).join(' '))}">
            <a class="project-card-link" href="${esc(p.url)}"${/^https?:/.test(p.url) ? ' target="_blank" rel="noopener"' : ''}>
              <span class="project-card-header">
                <span class="project-icon" aria-hidden="true">${p.icon}</span>
                ${ARROW}
              </span>
              <h4 class="project-card-title">${esc(p.title)}</h4>
              <p class="project-card-description">${esc(p.description)}</p>
            </a>
            <div class="project-card-footer">
              <span class="project-card-cta">${esc(p.cta)}</span>${repo}
            </div>
          </article>`;
}

function renderCategory(cat, projects) {
  const cards = projects.filter(p => p.category === cat.id).map(renderCard).join('\n\n');
  return `        <div class="project-category-wrapper" data-category="${esc(cat.id)}">
          <div class="category-header">
            <h3 class="category-title">${esc(cat.title)}</h3>
            <p class="category-description">${esc(cat.description)}</p>
          </div>
          <div class="project-grid">
${cards}
          </div>
        </div>`;
}

function renderControls(categories, total) {
  const chips = categories.map(c =>
    `            <button type="button" class="filter-chip" data-filter="${esc(c.id)}">${esc(c.title)}</button>`
  ).join('\n');

  // Hidden until JS upgrades it: without the script these controls do nothing,
  // and an inert search box is worse than no search box.
  return `        <div class="project-controls" id="project-controls" hidden>
          <div class="project-search">
            <label class="visually-hidden" for="project-search-input">Search projects</label>
            <input type="search" id="project-search-input" placeholder="Search ${total} projects..." autocomplete="off">
          </div>
          <div class="filter-chips" role="group" aria-label="Filter projects by category">
            <button type="button" class="filter-chip active" data-filter="all">All</button>
${chips}
          </div>
          <p class="project-result-count" id="project-result-count" role="status" aria-live="polite"></p>
        </div>`;
}

function main() {
  const { categories, projects } = JSON.parse(fs.readFileSync(DATA, 'utf8'));

  const orphans = projects.filter(p => !categories.some(c => c.id === p.category));
  if (orphans.length) {
    throw new Error(`Projects with an unknown category: ${orphans.map(p => p.id).join(', ')}`);
  }

  const body = [
    renderControls(categories, projects.length),
    ...categories.map(c => renderCategory(c, projects))
  ].join('\n\n');

  const html = fs.readFileSync(INDEX, 'utf8');
  const start = html.indexOf(START);
  const end = html.indexOf(END);
  if (start === -1 || end === -1) {
    throw new Error(`Markers not found in index.html. Expected:\n${START}\n${END}`);
  }

  const next = html.slice(0, start + START.length) + '\n' + body + '\n' + html.slice(end);
  fs.writeFileSync(INDEX, next);
  console.log(`Rendered ${projects.length} projects across ${categories.length} categories into index.html`);
}

main();
